-- 놀거리 계절·기간별 운영시간. 오늘 날짜가 들어가는 기간 중 가장 짧은 기간이 우선 (예: 연말 휴무 > 겨울 시간 > 기본)
-- start_md / end_md: 'MM-DD', 해를 넘기는 기간 가능 (예: 10-01 ~ 03-14)
-- open_time / close_time NULL: spots 기본값 사용
-- closed_days NULL: spots 기본 정기휴일 사용, 'NONE': 그 기간은 정기휴일 없음
-- is_closed = 1: 그 기간 전체 휴무
CREATE TABLE spot_hours (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spot_id     NUMBER(19) NOT NULL,
    start_md    VARCHAR2(5 CHAR) NOT NULL,
    end_md      VARCHAR2(5 CHAR) NOT NULL,
    open_time   VARCHAR2(5 CHAR),
    close_time  VARCHAR2(5 CHAR),
    closed_days VARCHAR2(30 CHAR),
    is_closed   NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_spot_hours_spot FOREIGN KEY (spot_id) REFERENCES spots (id) ON DELETE CASCADE,
    CONSTRAINT chk_spot_hours_closed CHECK (is_closed IN (0, 1))
);
CREATE INDEX idx_spot_hours_spot ON spot_hours (spot_id);
