-- 놀거리(명소): 신사·절, 공원·정원, 유원지·수족관·동물원, 전망·경치, 성·거리
-- hours_kind: ALWAYS(24시간) / FIXED(open_time~close_time) / VARIES(날마다 다름 → 공식 확인)
-- closed_days: 정기휴일 요일 (MON,TUE,...) 쉼표 구분, 없으면 NULL
CREATE TABLE spots (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100 CHAR) NOT NULL,
    name_ja         VARCHAR2(100 CHAR),
    kind            VARCHAR2(20 CHAR)  NOT NULL,
    prefecture      VARCHAR2(20 CHAR)  NOT NULL,
    city            VARCHAR2(50 CHAR)  NOT NULL,
    lat             NUMBER(9,6)        NOT NULL,
    lng             NUMBER(9,6)        NOT NULL,
    hours_kind      VARCHAR2(10 CHAR)  DEFAULT 'FIXED' NOT NULL,
    open_time       VARCHAR2(5 CHAR),
    close_time      VARCHAR2(5 CHAR),
    closed_days     VARCHAR2(30 CHAR),
    hours_note      VARCHAR2(200 CHAR),
    fee_note        VARCHAR2(100 CHAR),
    description     CLOB,
    tips            CLOB,
    google_place_id VARCHAR2(100 CHAR),
    official_url    VARCHAR2(500 CHAR),
    verified_at     DATE,
    image_url       VARCHAR2(500 CHAR),
    CONSTRAINT chk_spots_kind CHECK (kind IN ('SHRINE_TEMPLE', 'PARK_GARDEN', 'AMUSEMENT', 'VIEWPOINT', 'HISTORIC')),
    CONSTRAINT chk_spots_hours CHECK (hours_kind IN ('ALWAYS', 'FIXED', 'VARIES'))
);
CREATE INDEX idx_spots_lat_lng ON spots (lat, lng);
CREATE INDEX idx_spots_kind    ON spots (kind);
