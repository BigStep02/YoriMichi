-- 저장함(縁帳): 로그인 사용자가 저장한 축제·놀거리·맛집·코스
-- 맛집은 Google 장소 정보 장기 저장 금지 규칙 때문에 place_id만 저장하고,
-- 화면 표시는 우리 데이터(가까운 도시, 만난 곳, 메모)로 한다. 이름은 [인연 열기] 때 Details로 조회.
CREATE TABLE saved_items (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      NUMBER(19)         NOT NULL,
    item_type    VARCHAR2(20 CHAR)  NOT NULL,
    ref_key      VARCHAR2(400 CHAR) NOT NULL,
    festival_id  NUMBER(19),
    spot_id      NUMBER(19),
    place_id     VARCHAR2(300 CHAR),
    prefecture   VARCHAR2(20 CHAR),
    city         VARCHAR2(100 CHAR),
    met_type     VARCHAR2(20 CHAR),
    met_id       NUMBER(19),
    preset       VARCHAR2(40 CHAR),
    course_json  CLOB,
    memo         VARCHAR2(500 CHAR),
    visited      NUMBER(1) DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_saved_user     FOREIGN KEY (user_id)     REFERENCES app_users(id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_festival FOREIGN KEY (festival_id) REFERENCES festivals(id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_spot     FOREIGN KEY (spot_id)     REFERENCES spots(id)     ON DELETE CASCADE,
    CONSTRAINT uq_saved_items    UNIQUE (user_id, item_type, ref_key),
    CONSTRAINT chk_saved_type    CHECK (item_type IN ('RESTAURANT', 'FESTIVAL', 'SPOT', 'COURSE')),
    CONSTRAINT chk_saved_visited CHECK (visited IN (0, 1))
);

CREATE INDEX ix_saved_items_user ON saved_items (user_id, created_at);
