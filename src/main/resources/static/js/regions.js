/** '島根県', '出雲市' → '시마네 이즈모시' */
export function regionKo(prefecture, city) {
  const p = prefecture ? (PREF[prefecture] || prefecture) : '';
  const c = city ? (CITY[city] || city) : '';
  // '오사카 오사카시 주오구'처럼 겹치면 도도부현 생략
  if (p && c.startsWith(p)) return c;
  return [p, c].filter(Boolean).join(' ');
}
